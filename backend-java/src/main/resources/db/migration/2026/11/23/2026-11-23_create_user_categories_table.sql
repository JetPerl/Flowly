CREATE TABLE IF NOT EXISTS user_categories
(
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id      INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    custom_name      VARCHAR(255),
    custom_color     VARCHAR(50),
    custom_icon      VARCHAR(100),
    custom_parent_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
    sort_order       INTEGER,
    is_hidden        BOOLEAN DEFAULT false NOT NULL,
    is_customized    BOOLEAN DEFAULT false NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    CONSTRAINT uq_user_categories_user_category UNIQUE (user_id, category_id)
    );

CREATE INDEX IF NOT EXISTS idx_user_categories_user_id ON user_categories(user_id);