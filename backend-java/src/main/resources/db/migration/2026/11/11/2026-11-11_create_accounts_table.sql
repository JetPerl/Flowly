CREATE TABLE accounts
(
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name                VARCHAR(255) NOT NULL,
    short_name          VARCHAR(255),
    full_name           VARCHAR(255),
    account_group       VARCHAR(50),
    account_type        VARCHAR(50) DEFAULT 'cash' NOT NULL,
    type                VARCHAR(50) DEFAULT 'REGULAR',
    currency            VARCHAR(10) NOT NULL,
    balance             NUMERIC(19, 4) DEFAULT 0 NOT NULL,
    initial_balance     NUMERIC(19, 4) DEFAULT 0 NOT NULL,
    goal_target         NUMERIC(19, 4),
    goal_deadline       TIMESTAMP WITH TIME ZONE,
    icon                VARCHAR(100),
    color               VARCHAR(50),
    is_hidden           BOOLEAN DEFAULT false NOT NULL,
    is_archived         BOOLEAN DEFAULT false NOT NULL,
    is_active           BOOLEAN DEFAULT true NOT NULL,
    sort_order          INTEGER,
    fiat_rate           NUMERIC(18, 8),
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);